/**
 * Layered extraction pipeline for Cloudflare Workers:
 * 1. Native PDF text extraction via lightweight approach
 * 2. Cloudflare AI OCR fallback for scanned/image PDFs
 * 3. Image OCR for direct image uploads
 * 4. DOCX extraction via JSZip XML parsing
 * 5. TXT/CSV direct text extraction
 */

const ACCEPTED_EXTENSIONS = [
  ".pdf", ".png", ".jpg", ".jpeg", ".webp", ".heic", ".tiff", ".tif",
  ".docx", ".doc", ".txt", ".csv", ".xlsx", ".xls", ".xlsm",
];

export function isAcceptedExtension(filename: string): boolean {
  const ext = "." + filename.toLowerCase().split(".").pop();
  return ACCEPTED_EXTENSIONS.includes(ext);
}

export function getExtension(filename: string): string {
  return "." + filename.toLowerCase().split(".").pop();
}

/**
 * Extract text from a PDF by reading raw bytes and looking for text content.
 * This is a lightweight approach that works within Workers' 1MB code limit.
 * It handles native text PDFs by extracting embedded text streams.
 */
async function extractPdfNative(buffer: ArrayBuffer): Promise<string | null> {
  try {
    const bytes = new Uint8Array(buffer);
    const textContent: string[] = [];

    // PDF text objects are typically between BT and ET markers
    // We extract plain text from the raw PDF stream data
    const decoder = new TextDecoder("utf-8");
    let content = decoder.decode(buffer);

    // Try to find and extract text from PDF streams
    // First, try to decompress any FlateDecode streams
    // For simple PDFs, text may be embedded as plain text between parentheses
    
    // Extract text between parentheses in PDF content streams
    // This handles many basic PDFs generated by common tools
    const parenMatches = content.match(/\(([^)]*)\)/g);
    if (parenMatches) {
      for (const match of parenMatches) {
        const text = match.slice(1, -1)
          .replace(/\\n/g, "\n")
          .replace(/\\r/g, "\r")
          .replace(/\\t/g, "\t")
          .replace(/\\([0-7]{3})/g, (_, oct) => String.fromCharCode(parseInt(oct, 8)))
          .replace(/\\(.)/g, "$1")
          .trim();
        if (text.length > 1) {
          textContent.push(text);
        }
      }
    }

    // Also try to extract text from between BT...ET blocks
    const btEtRegex = /BT([\s\S]*?)ET/g;
    let btMatch;
    while ((btMatch = btEtRegex.exec(content)) !== null) {
      const block = btMatch[1];
      // Extract Tj and TJ operator text
      const tjMatches = block.match(/\(([^)]*)\)\s*Tj/g);
      if (tjMatches) {
        for (const tj of tjMatches) {
          const text = tj.match(/\(([^)]*)\)/)?.[1];
          if (text && text.trim().length > 1) {
            textContent.push(text);
          }
        }
      }
    }

    // Also try to decompress and extract - look for common PDF patterns
    // Stream objects may contain compressed text
    const streamMatches = content.match(/stream\s([\s\S]*?)\nendstream/g);
    if (streamMatches) {
      for (const stream of streamMatches) {
        const streamData = stream.replace(/^stream\s/, "").replace(/\nendstream$/, "");
        // Try to detect if it looks like raw text (not compressed)
        if (/^[\x20-\x7E\n\r\t]+$/.test(streamData.substring(0, 100))) {
          textContent.push(streamData.trim());
        }
      }
    }

    const extracted = textContent.join("\n").replace(/\s+/g, " ").trim();
    if (extracted.length > 50) {
      return extracted;
    }

    return null;
  } catch (err) {
    console.log(`[Extractor] Native PDF extraction failed: ${err instanceof Error ? err.message : "Unknown"}`);
    return null;
  }
}

/**
 * OCR via Cloudflare Workers AI for images
 */
async function ocrImage(imageBuffer: ArrayBuffer, env: Env): Promise<string | null> {
  try {
    const base64 = arrayBufferToBase64(imageBuffer);
    const result = await env.AI.run("@cf/unisys/ocr", {
      imageBase64: base64,
    });
    const text = (result as { text?: string }).text ?? "";
    return text.trim().length > 10 ? text.trim() : null;
  } catch (err) {
    console.log(`[Extractor] Cloudflare AI OCR failed: ${err instanceof Error ? err.message : "Unknown"}`);
    return null;
  }
}

