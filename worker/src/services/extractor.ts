function arrayBufferToBase64(buffer: ArrayBuffer): string {
  if (typeof globalThis !== 'undefined' && (globalThis as any).Buffer) {
    return (globalThis as any).Buffer.from(buffer).toString('base64');
  }
  const bytes = new Uint8Array(buffer);
  let binary = "";
  const chunk = 8192;
  for (let i = 0; i < bytes.length; i += chunk) {
    const slice = bytes.subarray(i, i + chunk);
    binary += String.fromCharCode.apply(null, slice as unknown as number[]);
  }
  return btoa(binary);
}

/**
 * Extract text from TXT files
 */
function extractFromTxt(buffer: ArrayBuffer): ExtractionResult {
  const decoder = new TextDecoder("utf-8");
  const text = decoder.decode(buffer).trim();
  const pages = Math.max(1, Math.ceil(text.length / 2500));
  const lineItems = text.split("\n").filter((l) => l.trim().length > 0).length;
  return {
    text,
    pages,
    lineItems,
    fileType: "txt",
    extractionMethod: "native",
    confidenceScore: 100,
  };
}

/**
 * Extract text from CSV (simple parsing)
 */
function extractFromCsv(buffer: ArrayBuffer): ExtractionResult {
  const decoder = new TextDecoder("utf-8");
  const raw = decoder.decode(buffer);
  const lines = raw.split("\n").filter((l) => l.trim().length > 0);
  const text = lines.join("\n");
  const lineItems = lines.length;
  return {
    text,
    pages: 1,
    lineItems,
    fileType: "spreadsheet",
    extractionMethod: "native",
    confidenceScore: 100,
  };
}

/**
 * Main PDF extraction function with layered pipeline.
 * Priority: native text > OCR fallback
 */
export async function extractPdf(
  buffer: ArrayBuffer,
  env: Env,
  fileName: string = "document.pdf"
): Promise<ExtractionResult> {
  // Phase 1: Native text extraction (lightweight, handles most text-based PDFs)
  const nativeText = await extractPdfNative(buffer);
  if (nativeText) {
    const lineItems = nativeText.split("\n").filter((l) => l.trim().length > 0).length;
    return {
      text: nativeText,
      pages: 1,
      lineItems,
      fileType: "pdf",
      extractionMethod: "native",
      confidenceScore: 90,
    };
  }

  // Phase 2: Try direct Gemini PDF Vision OCR if configured
  const apiKey = env.GEMINI_API_KEY || env.GOOGLE_API_KEY;
  if (apiKey) {
    try {
      console.log(`[Extractor] Attempting direct Gemini PDF Vision OCR for ${fileName}...`);
      const base64 = arrayBufferToBase64(buffer);
      const text = await extractPdfViaGemini(base64, env);
      const lineItems = text.split("\n").filter((l) => l.trim().length > 0).length;
      return {
        text,
        pages: 1,
        lineItems,
        fileType: "pdf",
        extractionMethod: "gemini-pdf-ocr",
        confidenceScore: 95,
      };
    } catch (err) {
      console.error(`[Extractor] Gemini PDF OCR failed, falling back to local OCR:`, err);
    }
  }

  // Phase 3: Cloudflare AI OCR fallback (for scanned/image-based PDFs)
  const ocrText = await extractPdfViaOcr(buffer, env);
  if (ocrText) {
    const lineItems = ocrText.split("\n").filter((l) => l.trim().length > 0).length;
    return {
      text: ocrText,
      pages: 1,
      lineItems,
      fileType: "pdf",
      extractionMethod: "ocr",
      confidenceScore: 75,
    };
  }

  throw errors.badFile("Could not extract text from this PDF. It may be a scanned document or the file may be corrupted. Try uploading a clearer scan or image format (PNG/JPG).");
}

/**
 * Extract text from an image using Cloudflare AI OCR
 */
export async function extractImage(
  buffer: ArrayBuffer,
  env: Env,
  fileName: string = "image.png"
): Promise<ExtractionResult> {
  const apiKey = env.GEMINI_API_KEY || env.GOOGLE_API_KEY;

  if (apiKey) {
    try {
      console.log(`[Extractor] Attempting high-speed Gemini OCR for ${fileName}...`);
      const mimeType = detectMimeType(buffer, fileName);
      const base64 = arrayBufferToBase64(buffer);
      const text = await extractImageViaGemini(base64, mimeType, env);

      const lineItems = text.split("\n").filter((l) => l.trim().length > 0).length;
      return {
        text,
        pages: 1,
        lineItems,
        fileType: "image",
        extractionMethod: "gemini-ocr",
        confidenceScore: 95,
      };
    } catch (err) {
      console.error(`[Extractor] Gemini OCR failed, falling back to local OCR:`, err);
    }
  }

  console.log(`[Extractor] Falling back to local Cloudflare AI OCR for ${fileName}...`);
  const ocrText = await ocrImage(buffer, env);
  if (ocrText) {
    const lineItems = ocrText.split("\n").filter((l) => l.trim().length > 0).length;
    return {
      text: ocrText,
      pages: 1,
      lineItems,
      fileType: "image",
      extractionMethod: "image-ocr",
      confidenceScore: 75,
    };
  }

  throw errors.badFile("Could not extract text from this image. Try a clearer scan or a different format.");
}

/**
 * Extract text from a DOCX using JSZip XML parsing (Workers-compatible).
 */
export async function extractDocx(buffer: ArrayBuffer): Promise<ExtractionResult> {
  try {
    // DOCX is a ZIP file containing XML. We extract text from word/document.xml
    const JSZip = (await import("jszip")).default;
    const zip = await JSZip.loadAsync(buffer);
    const docFile = zip.file("word/document.xml");
    if (!docFile) {
      throw new Error("No document.xml found in DOCX");
    }
    const xmlContent = await docFile.async("text");
    // Simple XML text extraction — strip tags, keep content
    const text = xmlContent
      .replace(/<[^>]*>/g, " ")
      .replace(/&/g, "&")
      .replace(/</g, "<")
      .replace(/>/g, ">")
      .replace(/"/g, '"')
      .replace(/&#39;/g, "'")
      .replace(/&#x27;/g, "'")
      .replace(/&#x2019;/g, "'")
      .replace(/&#x2013;/g, "-")
      .replace(/&#x2014;/g, "--")
      .replace(/\s+/g, " ")
      .trim();

    const pages = Math.max(1, Math.ceil(text.length / 2500));
    const lineItems = text.split("\n").filter((l) => l.trim().length > 0).length;
    return { text, pages, lineItems, fileType: "docx", extractionMethod: "native", confidenceScore: 90 };
  } catch (err) {
    console.error("[Extractor] DOCX extraction failed:", err);
    throw errors.badFile("Could not extract text from this DOCX file.");
  }
}

/**
 * Main dispatcher — detect file type and route to the right extractor
 */
export async function extractText(
  buffer: ArrayBuffer,
  fileName: string,
  env: Env
): Promise<ExtractionResult> {
  const ext = getExtension(fileName);

  switch (ext) {
    case ".pdf":
      return extractPdf(buffer, env, fileName);
    case ".png":
    case ".jpg":
    case ".jpeg":
    case ".webp":
    case ".tiff":
    case ".tif":
    case ".heic":
      return extractImage(buffer, env, fileName);
    case ".docx":
    case ".doc":
      return extractDocx(buffer);
    case ".txt":
      return extractFromTxt(buffer);
    case ".csv":
      return extractFromCsv(buffer);
    case ".xlsx":
    case ".xls":
    case ".xlsm":
      // XLSX is a ZIP format — try to extract text from shared strings
      try {
        const JSZip = (await import("jszip")).default;
        const zip = await JSZip.loadAsync(buffer);
        const sharedStrings = zip.file("xl/sharedStrings.xml");
        if (sharedStrings) {
          const xmlContent = await sharedStrings.async("text");
          const text = xmlContent
            .replace(/<[^>]*>/g, " ")
            .replace(/&/g, "&")
            .replace(/</g, "<")
            .replace(/>/g, ">")
            .replace(/"/g, '"')
            .replace(/&#39;/g, "'")
            .replace(/\s+/g, " ")
            .trim();
          if (text.length > 10) {
            const lineItems = text.split("\n").filter((l) => l.trim().length > 0).length;
            return { text, pages: 1, lineItems, fileType: "spreadsheet", extractionMethod: "native", confidenceScore: 85 };
          }
        }
        // Fallback to sheet data
        const sheetFile = zip.file("xl/worksheets/sheet1.xml");
        if (sheetFile) {
          const xmlContent = await sheetFile.async("text");
          const text = xmlContent
            .replace(/<[^>]*>/g, " ")
            .replace(/&/g, "&")
            .replace(/</g, "<")
            .replace(/>/g, ">")
            .replace(/\s+/g, " ")
            .trim();
          if (text.length > 10) {
            const lineItems = text.split("\n").filter((l) => l.trim().length > 0).length;
            return { text, pages: 1, lineItems, fileType: "spreadsheet", extractionMethod: "native", confidenceScore: 80 };
          }
        }
      } catch {
        // fallback to raw text extraction
      }
      return extractFromTxt(buffer);
    default:
      throw errors.unsupportedType(ext);
  }
}